// 构建：把 runtime.js 注入 client.src.js → client.js（iframe 与无头浏览器 browser.js 共用同一份检查脚本）
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
const here = dirname(fileURLToPath(import.meta.url))
const runtime = readFileSync(join(here, 'runtime.js'), 'utf8')
if (/<\/script/i.test(runtime)) throw new Error('runtime.js must not contain </script')
const src = readFileSync(join(here, 'client.src.js'), 'utf8')
const marker = "/*__RUNTIME_SOURCE__*/''"
if (!src.includes(marker)) throw new Error('marker missing')
writeFileSync(join(here, 'client.js'), '// GENERATED by build.mjs from client.src.js + runtime.js — edit those files instead.\n' + src.replace(marker, () => JSON.stringify(runtime)), 'utf8')
console.log('client.js built', (runtime.length / 1024).toFixed(1) + 'KB runtime')
